def cell_rows(c):
    """7 strings of 5 chars ('#'/'.') for character code c."""
    if c >= 0x80:
        return ldglyphs.glyph_rows(c)
    if 0x20 <= c <= 0x7E:
        cols = _ASCII[(c - 0x20) * 5:(c - 0x20) * 5 + 5]
        return ["".join("#" if (cols[x] >> y) & 1 else "." for x in range(5)) for y in range(7)]
    return ldglyphs.blank()


def render_png(buf, path=None, scale=6, gap_x=1, gap_y=3, frames=None, duration=120):
    """Render a 40-byte buffer (or a list of buffers via frames=) to PNG / animated GIF."""
    from PIL import Image, ImageDraw
    pitch_x = 5 + gap_x
    pitch_y = 7 + gap_y
    w = (COLS * pitch_x - gap_x + 4) * scale
    h = (ROWS * pitch_y - gap_y + 4) * scale
    on, off, bg = (110, 255, 225), (22, 38, 38), (6, 10, 12)

    def draw(b):
        img = Image.new("RGB", (w, h), bg)
        d = ImageDraw.Draw(img)
        for i in range(ROWS * COLS):
            rows = cell_rows(b[i])
            cx, cy = (i % COLS) * pitch_x + 2, (i // COLS) * pitch_y + 2
            for y in range(7):
                for x in range(5):
                    px, py = (cx + x) * scale, (cy + y) * scale
                    d.ellipse([px + 1, py + 1, px + scale - 1, py + scale - 1],
                              fill=on if rows[y][x] == "#" else off)
        return img

    if frames:
        imgs = [draw(f) for f in frames]
        imgs[0].save(path, save_all=True, append_images=imgs[1:], duration=duration, loop=0)
        return imgs[0]
    img = draw(buf)
    if path:
        img.save(path)
    return img


def render_term(buf):
    """Terminal rendering with half-block characters (2 dot rows per text line)."""
    lines = []
    for r in range(ROWS):
        cells = [cell_rows(buf[r * COLS + c]) for c in range(COLS)]
        dots = ["".join(cells[c][y] + "." for c in range(COLS)) for y in range(7)] + ["." * (COLS * 6)]
        for y in range(0, 8, 2):
            top, bot = dots[y], dots[y + 1]
            lines.append("".join(
                "█" if a == "#" and b == "#" else "▀" if a == "#" else "▄" if b == "#" else " "
                for a, b in zip(top, bot)))
    return "\n".join(lines)
